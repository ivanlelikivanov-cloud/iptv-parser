HEADERS = {
    'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 '
                  '(KHTML, like Gecko) Chrome/128.0.0.0 Safari/537.36'
}

CACHE_DURATION = 1800  # 30 минут
playlist_cache = "#EXTM3U\n# Generated by IPTV Aggregator Pro\n"
cache_timestamp = 0
stats = {"total_channels": 0, "sources_processed": 0, "last_update": ""}

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

# ==================== ASYNC FETCHER ====================
async def fetch_playlist(session, url, priority):
    try:
        async with session.get(url, timeout=20, headers=HEADERS) as resp:
            if resp.status != 200:
                return []
            text = await resp.text()
            return parse_m3u(text, priority)
    except Exception as e:
        logger.warning(f"Failed {url}: {e}")
        return []


def parse_m3u(content: str, priority: int):
    channels = []
    lines = content.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        if line.startswith("#EXTINF:"):
            # Извлекаем tvg-name, tvg-id, group-title и название
            inf = line
            tvg_name = None
            tvg_id = None
            group = "Other"

            if 'tvg-name="' in inf:
                tvg_name = inf.split('tvg-name="')[1].split('"')[0]
            if 'tvg-id="' in inf:
                tvg_id = inf.split('tvg-id="')[1].split('"')[0]
            if 'group-title="' in inf:
                group = inf.split('group-title="')[1].split('"')[0]

            name = tvg_name or inf.split(',')[-1].strip()

            i += 1
            if i < len(lines) and lines[i].strip().startswith("http"):
                url = lines[i].strip()
                channels.append({
                    "url": url,
                    "inf": inf,
                    "name": name,
                    "tvg_id": tvg_id,
                    "tvg_name": tvg_name,
                    "group": group,
                    "priority": priority
                })
        i += 1
    return channels


async def update_cache():
    global playlist_cache, cache_timestamp, stats
    start = time.time()

    async with aiohttp.ClientSession() as session:
        tasks = [fetch_playlist(session, url, prio) for url, prio in SOURCES]
        results = await asyncio.gather(*tasks, return_exceptions=True)

    # Умная дедупликация
    seen = OrderedDict()
    for result in results:
        if isinstance(result, Exception):
            continue
        for ch in result:
            key = (ch["tvg_id"] or ch["tvg_name"] or ch["url"], ch["url"])
            if key not in seen or ch["priority"] > seen[key]["priority"]:
                seen[key] = ch

    # Сборка плейлиста
    lines = ["#EXTM3U", f"# Generated: {time.strftime('%Y-%m-%d %H:%M:%S')}", 
             f"# Total channels: {len(seen)}"]
    
    for ch in seen.values():
        lines.append(ch["inf"])
        lines.append(ch["url"])

    playlist_cache = "\n".join(lines)
    cache_timestamp = time.time()
    
    stats.update({
        "total_channels": len(seen),
        "sources_processed": len([r for r in results if not isinstance(r, Exception)]),
        "last_update": time.strftime("%Y-%m-%d %H:%M:%S")
    })
    
    logger.info(f"Cache updated: {len(seen)} channels in {time.time()-start:.1f}s")


def background_updater():
    while True:
        try:
            asyncio.run(update_cache())
        except Exception as e:
            logger.error(f"Updater error: {e}")
        time.sleep(CACHE_DURATION)


