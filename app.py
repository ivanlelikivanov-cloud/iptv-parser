@app.route('/playlist.m3u')
@app.route('/iptv.m3u')
def get_playlist():
    if time.time() - cache_timestamp > CACHE_DURATION + 300:
        threading.Thread(target=lambda: asyncio.run(update_cache()), daemon=True).start()
    return Response(playlist_cache, mimetype='application/vnd.apple.mpegurl')


@app.route('/api/channels')
def api_channels():
    # Простой парсинг для API
    channels = []
    for line in playlist_cache.splitlines():
        if line.startswith("#EXTINF:"):
            name = line.split(',')[-1].strip() if ',' in line else "Unknown"
            channels.append({"name": name})
    return jsonify({"channels": channels[:500], "total": stats["total_channels"]})  # лимит для удобства


@app.route('/health')
def health():
    return jsonify({
        "status": "healthy",
        "channels": stats["total_channels"],
        "uptime_seconds": int(time.time() - cache_timestamp)
    })


